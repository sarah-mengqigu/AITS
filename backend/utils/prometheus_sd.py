"""Prometheus File SD integration for AITS.

The performance module registers the load-generator host into Prometheus so the
Windows Exporter on the pressure machine is scraped automatically. The outbound
IPv4 is discovered with a UDP "dummy" connect (no packet is actually sent).
"""

from __future__ import annotations

import json
import logging
import os
import socket
import tempfile
from pathlib import Path

from django.conf import settings

logger = logging.getLogger(__name__)

DEFAULT_LABELS = {"instance": "AITS-Generator", "role": "load-generator"}


def get_local_ipv4() -> str:
    """Return the outbound IPv4 address, falling back to 127.0.0.1."""
    sock = None
    try:
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        sock.settimeout(1.0)
        # No traffic is generated by connect() on UDP; it only selects a route.
        sock.connect(("8.8.8.8", 80))
        return sock.getsockname()[0]
    except OSError as exc:  # offline environments
        logger.debug("outbound IP discovery failed: %s", exc)
        return "127.0.0.1"
    finally:
        if sock is not None:
            sock.close()


def targets_file_path() -> Path:
    configured = getattr(settings, "PROMETHEUS_TARGETS_FILE", "")
    if configured:
        return Path(configured)
    return Path(settings.BASE_DIR) / "aits_monitor" / "prometheus" / "targets.json"


def build_target(ip: str, port: int, labels: dict | None = None) -> dict:
    return {
        "targets": [f"{ip}:{port}"],
        "labels": dict(labels or DEFAULT_LABELS),
    }


def update_windows_exporter_target(ip: str | None = None, port: int | None = None,
                                   path: str | Path | None = None,
                                   force: bool = False) -> dict:
    """Write the Windows Exporter target file used by ``file_sd_configs``.

    Returns ``{"enabled": bool, "path": str, "targets": [...]}``. When
    ``PROMETHEUS_SD_AUTO_UPDATE`` is disabled and ``force`` is False nothing is
    written and ``enabled`` is False.
    """
    enabled = bool(getattr(settings, "PROMETHEUS_SD_AUTO_UPDATE", True)) or force
    target_path = Path(path) if path else targets_file_path()
    if not enabled:
        return {"enabled": False, "path": str(target_path), "targets": []}

    resolved_ip = ip or get_local_ipv4()
    resolved_port = int(port or getattr(settings, "WINDOWS_EXPORTER_PORT", 9182))
    payload = [build_target(resolved_ip, resolved_port)]

    target_path.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write_json(target_path, payload)
    logger.info("prometheus file SD updated: %s -> %s", target_path, payload)
    return {"enabled": True, "path": str(target_path), "targets": payload}


def _atomic_write_json(path: Path, payload) -> None:
    handle, tmp_name = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as fh:
            json.dump(payload, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        os.replace(tmp_name, path)
    except Exception:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)
        raise


def read_targets(path: str | Path | None = None) -> list:
    target_path = Path(path) if path else targets_file_path()
    if not target_path.exists():
        return []
    try:
        return json.loads(target_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
