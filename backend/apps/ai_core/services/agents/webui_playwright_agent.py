"""webui_playwright Agent：把 UI 用例/需求 + POM 转换为可编译的 Playwright Python 脚本。"""

from __future__ import annotations

import json
from typing import Any, TypedDict

from apps.ai_core.services.agents.base import BaseAgent
from apps.common.parsers.yaml_json import strip_code_fence


class PlaywrightState(TypedDict, total=False):
    payload: dict
    project: Any
    prompt: str
    retrieved: list
    llm_text: str
    llm_data: Any
    usage: list
    result: Any


def _py(value) -> str:
    """Render a python string literal (safe for arbitrary user text)."""
    return json.dumps("" if value is None else str(value), ensure_ascii=False)


def _wait_ms(value) -> int:
    try:
        return max(0, int(float(str(value))))
    except (TypeError, ValueError):
        return 500


def build_playwright_script(payload: dict) -> str:
    """Deterministic, syntactically valid Playwright script."""
    case = payload.get("case") if isinstance(payload.get("case"), dict) else {}
    steps = case.get("steps") if isinstance(case.get("steps"), list) else payload.get("steps")
    steps = [step for step in (steps or []) if isinstance(step, dict)]
    base_url = (
        payload.get("base_url")
        or case.get("base_url")
        or "https://example.com"
    )
    pom = payload.get("pom") if isinstance(payload.get("pom"), dict) else {}
    page_names = [
        str(page.get("name"))
        for page in (pom.get("pages") or [])
        if isinstance(page, dict) and page.get("name")
    ]

    lines = [
        '"""Playwright script generated by AITS webui_playwright agent."""',
        "from playwright.sync_api import sync_playwright",
        "",
        "",
        "def run(page):",
    ]
    if page_names:
        lines.append(f"    # POM pages: {', '.join(page_names)}")
    lines.append(f"    page.goto({_py(base_url)})")
    for step in steps:
        action = str(step.get("action") or "click").lower()
        target = step.get("target") or ""
        value = step.get("value", "")
        expect = str(step.get("expect") or "").replace("\n", " ")[:120]
        if action == "goto":
            line = f"    page.goto({_py(target or base_url)})"
        elif action == "click":
            line = f"    page.click({_py(target)})"
        elif action in ("fill", "input"):
            line = f"    page.fill({_py(target)}, {_py(value)})"
        elif action == "select":
            line = f"    page.select_option({_py(target)}, {_py(value)})"
        elif action == "hover":
            line = f"    page.hover({_py(target)})"
        elif action == "scroll":
            line = f"    page.mouse.wheel(0, {_wait_ms(value) or 500})"
        elif action == "press":
            line = f"    page.keyboard.press({_py(value or target)})"
        elif action == "upload":
            line = f"    page.set_input_files({_py(target)}, {_py(value)})"
        elif action == "js":
            line = f"    page.evaluate({_py(value or target)})"
        elif action == "wait":
            line = f"    page.wait_for_timeout({_wait_ms(value)})"
        elif action in ("expect", "assert"):
            line = f"    page.wait_for_selector({_py(target)})"
        else:
            line = f"    page.click({_py(target)})"
        if expect:
            line = f"{line}  # {expect}"
        lines.append(line)

    lines.extend(
        [
            "",
            "",
            "def test_generated_case():",
            "    with sync_playwright() as p:",
            "        browser = p.chromium.launch(headless=True)",
            "        context = browser.new_context()",
            "        page = context.new_page()",
            "        try:",
            "            run(page)",
            "        finally:",
            "            context.close()",
            "            browser.close()",
            "",
            "",
            'if __name__ == "__main__":',
            "    test_generated_case()",
        ]
    )
    return "\n".join(lines) + "\n"


def _compiles(script: str) -> bool:
    try:
        compile(script, "<aits-generated-script>", "exec")
        return True
    except SyntaxError:
        return False


class WebUIPlaywrightAgent(BaseAgent):
    name = "webui_playwright"
    description = "根据 UI 用例/需求与 POM 生成语法正确的 Playwright Python 自动化脚本"
    stream_channel = "webui_auto_test"
    task_type = "webui_playwright"
    state_schema = PlaywrightState

    def retrieval_query(self, state) -> str:
        payload = state.get("payload") or {}
        case = payload.get("case") if isinstance(payload.get("case"), dict) else {}
        return " ".join(
            str(part)
            for part in (case.get("name"), payload.get("requirement"))
            if part
        )

    def build_prompt(self, payload: dict) -> str:
        case = payload.get("case") if isinstance(payload.get("case"), dict) else {}
        return (
            f"[agent:{self.name}]\n"
            "请生成 Python Playwright 脚本（from playwright.sync_api import sync_playwright）。\n"
            f"用例：{json.dumps(case, ensure_ascii=False, default=str)}\n"
            f"需求：{payload.get('requirement') or ''}\n"
            f"POM：{json.dumps(payload.get('pom') or {}, ensure_ascii=False, default=str)}\n"
            '仅返回 JSON：{"script": "<python code>", "language": "python"}'
        )

    def compose_result(self, payload: dict, llm_data, state) -> dict:
        case = payload.get("case") if isinstance(payload.get("case"), dict) else {}
        steps = case.get("steps") if isinstance(case.get("steps"), list) else payload.get("steps")
        step_targets = [
            str(step.get("target"))
            for step in (steps or [])
            if isinstance(step, dict) and step.get("target")
        ]
        candidate = None
        if isinstance(llm_data, dict):
            candidate = llm_data.get("script") or llm_data.get("content")
        if not candidate:
            text = str(state.get("llm_text") or "")
            if "playwright" in text and "import" in text:
                candidate = strip_code_fence(text)
        if candidate is not None:
            candidate = strip_code_fence(str(candidate))
        # Only accept an LLM script that actually covers the supplied steps.
        if candidate and step_targets and not any(
            target in candidate for target in step_targets
        ):
            candidate = None
        if not candidate or not _compiles(candidate):
            candidate = build_playwright_script(payload)
        if not _compiles(candidate):  # pragma: no cover - deterministic template guard
            candidate = (
                '"""Playwright script generated by AITS webui_playwright agent."""\n'
                "from playwright.sync_api import sync_playwright\n\n\n"
                "def run(page):\n    page.goto('https://example.com')\n"
            )
        return {
            "script": candidate,
            "language": "python",
            "valid": _compiles(candidate),
            "lines": len(candidate.splitlines()),
        }
